import { Prisma, PrismaClient } from '@prisma/client';
import { DdlCatalog, loadDdlCatalog, orderByDependency } from './schema-ddl';

/**
 * schema-drift.ts — runtime schema drift detection and additive repair
 * =============================================================================
 *
 * THE PROBLEM THIS SOLVES
 * -----------------------
 * ALUMFAB POS ships a template `pos.db` and copies it to
 * `%APPDATA%\ALUMFAB-POS\database\pos.db` on first launch — but only when the
 * file is missing. Every launch after that, the runtime database is whatever
 * the shop already had. Add a column to `schema.prisma`, run `db push` on the
 * dev box, ship the build, and the shop's database still has the old shape.
 *
 * Prisma then fails at the worst possible moment. It is not just writes: after
 * `product.update()` Prisma reads the row back with an explicit column list, so
 * a query that never mentions the new column still throws
 *
 *     P2022: The column `costPricePaise` does not exist in the current database
 *
 * mid-transaction, and the whole bulk import rolls back. That is exactly the
 * ODS ingestion failure this module exists to prevent.
 *
 * THE APPROACH
 * ------------
 * `Prisma.dmmf` is the datamodel embedded in the generated client. It is
 * regenerated by `prisma generate` on every build, so it cannot fall out of
 * sync with `schema.prisma` the way a hand-maintained migration list can. We
 * compare it against SQLite's `PRAGMA table_info` and classify each difference:
 *
 *   ADDITIVE  — something we can create losslessly: a missing column via
 *               ALTER TABLE, or a missing table via the DDL recorded in
 *               prisma/migrations. Repaired automatically, after a backup.
 *   BLOCKING  — a required column with no usable default, a type change, or a
 *               missing table we have no recorded DDL for. Never guessed at;
 *               the app refuses to start and tells the technician what to run.
 *   INFO      — a column in the database that the schema no longer knows
 *               about. Harmless: Prisma names its columns explicitly.
 *
 * MISSING TABLES
 * --------------
 * A CREATE TABLE needs exact column order, constraints, defaults and every
 * foreign key clause with the right ON DELETE / ON UPDATE action. Deriving that
 * from the datamodel means re-implementing Prisma's SQLite DDL generator, so
 * this module does not try. It reads the statements Prisma already wrote to
 * prisma/migrations (see schema-ddl.ts) and replays them verbatim. If the
 * catalog is unavailable — a partial checkout, or a build that forgot to ship
 * the resource — missing tables stay BLOCKING.
 *
 * Deliberately NOT handled: dropping columns, renaming, narrowing types. Those
 * need a real migration with a data plan, not a guess made at 8am while a
 * queue forms at the till.
 */

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export type DriftSeverity = 'additive' | 'blocking' | 'info';

export interface DriftItem {
  severity: DriftSeverity;
  table: string;
  column?: string;
  kind:
    | 'missing-column'
    | 'missing-table'
    | 'type-mismatch'
    | 'extra-column'
    | 'missing-unique-index';
  detail: string;
  /** SQL that fixes this item. Only ever populated for `additive`. */
  sql?: string[];
}

export interface DriftReport {
  ok: boolean;
  /** True when every item is additive or info — safe to auto-repair. */
  repairable: boolean;
  items: DriftItem[];
  additive: DriftItem[];
  blocking: DriftItem[];
  /**
   * Flat, ordered list of statements that repairs all additive drift.
   * Tables are created before the columns of already-existing tables are
   * altered, and referenced tables before their dependents.
   */
  repairSql: string[];
  /** Where the recorded DDL came from, or null when no catalog was found. */
  ddlSource: string | null;
}

export interface AnalyseOptions {
  /** `app.getAppPath()` — lets the catalog resolve in a dev checkout. */
  appPath?: string;
  /** `process.resourcesPath` — lets it resolve in a packaged build. */
  resourcesPath?: string;
  /** Pre-loaded catalog, mainly for tests. */
  catalog?: DdlCatalog;
}

interface ExpectedColumn {
  name: string;
  /** SQLite column type Prisma would have used. */
  sqliteType: string;
  required: boolean;
  isUnique: boolean;
  isId: boolean;
  /** Literal SQL for DEFAULT, or null when the field has no usable default. */
  defaultSql: string | null;
  isUpdatedAt: boolean;
}

// ---------------------------------------------------------------------------
// Prisma scalar -> SQLite storage type
// ---------------------------------------------------------------------------
// Mirrors the mapping the Prisma SQLite connector emits in its migrations.
const SQLITE_TYPE: Record<string, string> = {
  String: 'TEXT',
  Boolean: 'BOOLEAN',
  Int: 'INTEGER',
  BigInt: 'BIGINT',
  Float: 'REAL',
  Decimal: 'DECIMAL',
  DateTime: 'DATETIME',
  Bytes: 'BLOB',
  Json: 'JSONB'
};

/**
 * SQLite is loosely typed and reports whatever text was in the CREATE TABLE
 * statement, so comparisons must be forgiving. These are treated as the same
 * storage class.
 */
const TYPE_ALIASES: Record<string, string> = {
  TEXT: 'TEXT',
  CLOB: 'TEXT',
  VARCHAR: 'TEXT',
  CHARACTER: 'TEXT',
  INTEGER: 'INTEGER',
  INT: 'INTEGER',
  BIGINT: 'INTEGER',
  BOOLEAN: 'INTEGER',
  TINYINT: 'INTEGER',
  REAL: 'REAL',
  DOUBLE: 'REAL',
  FLOAT: 'REAL',
  NUMERIC: 'REAL',
  DECIMAL: 'REAL',
  DATETIME: 'DATETIME',
  DATE: 'DATETIME',
  TIMESTAMP: 'DATETIME',
  BLOB: 'BLOB',
  JSONB: 'TEXT',
  JSON: 'TEXT'
};

function normaliseType(raw: string): string {
  const base = (raw || '').toUpperCase().replace(/\(.*\)$/, '').trim();
  return TYPE_ALIASES[base] ?? base;
}

// ---------------------------------------------------------------------------
// Default value rendering
// ---------------------------------------------------------------------------

/**
 * Render a DMMF default as a SQL literal usable in ALTER TABLE ADD COLUMN.
 * Returns null when the default cannot be expressed as a column default —
 * `cuid()`, `uuid()` and `autoincrement()` are generated by Prisma or by the
 * table definition, not by a DEFAULT clause.
 */
function renderDefault(field: Prisma.DMMF.Field): string | null {
  if (!field.hasDefaultValue) return null;
  const def = field.default as unknown;

  // Function defaults: { name: 'now', args: [] }
  if (def && typeof def === 'object' && 'name' in (def as Record<string, unknown>)) {
    const fnName = (def as { name: string }).name;
    if (fnName === 'now') return 'CURRENT_TIMESTAMP';
    // cuid / uuid / autoincrement / dbgenerated cannot be a column default.
    return null;
  }

  switch (typeof def) {
    case 'number':
      return String(def);
    case 'boolean':
      return def ? 'true' : 'false';
    case 'string':
      // Covers String defaults and enum members (stored as TEXT in SQLite).
      return `'${def.replace(/'/g, "''")}'`;
    default:
      return null;
  }
}

// ---------------------------------------------------------------------------
// Expected shape, derived from the generated client
// ---------------------------------------------------------------------------

function expectedTables(): Map<string, ExpectedColumn[]> {
  const tables = new Map<string, ExpectedColumn[]>();

  for (const model of Prisma.dmmf.datamodel.models) {
    const tableName = model.dbName || model.name;
    const columns: ExpectedColumn[] = [];

    for (const field of model.fields) {
      // Relation fields are not columns. The foreign key scalar (e.g.
      // `categoryId`) is a separate scalar field and is picked up below.
      if (field.kind === 'object') continue;
      if (field.isList) continue;

      const sqliteType = field.kind === 'enum' ? 'TEXT' : SQLITE_TYPE[field.type] ?? 'TEXT';

      columns.push({
        name: field.dbName || field.name,
        sqliteType,
        required: field.isRequired,
        isUnique: Boolean(field.isUnique),
        isId: Boolean(field.isId),
        defaultSql: renderDefault(field),
        isUpdatedAt: Boolean(field.isUpdatedAt)
      });
    }

    tables.set(tableName, columns);
  }

  return tables;
}

// ---------------------------------------------------------------------------
// Live database introspection
// ---------------------------------------------------------------------------

interface PragmaColumn {
  cid: number;
  name: string;
  type: string;
  notnull: number;
  dflt_value: string | null;
  pk: number;
}

async function liveTables(client: PrismaClient): Promise<Set<string>> {
  const rows = await client.$queryRawUnsafe<{ name: string }[]>(
    "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
  );
  return new Set(rows.map((r) => r.name));
}

async function liveColumns(client: PrismaClient, table: string): Promise<PragmaColumn[]> {
  // PRAGMA does not accept bound parameters; the table name comes from our own
  // DMMF-derived list, never from user input.
  return client.$queryRawUnsafe<PragmaColumn[]>(`PRAGMA table_info("${table}")`);
}

