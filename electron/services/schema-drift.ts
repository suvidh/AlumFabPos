// Analysis
// ---------------------------------------------------------------------------

/**
 * Compare the connected database against the generated Prisma datamodel.
 *
 * Read-only: this never modifies the database.
 */
export async function analyseDrift(
  client: PrismaClient,
  options: AnalyseOptions = {}
): Promise<DriftReport> {
  const items: DriftItem[] = [];
  const expected = expectedTables();
  const present = await liveTables(client);

  const catalog = options.catalog ?? loadDdlCatalog(options.appPath, options.resourcesPath);

  // Missing tables are collected first so they can be emitted ahead of every
  // ALTER, and ordered so a referenced table exists before its dependents.
  const missingTables: string[] = [];

  for (const [table, columns] of expected) {
    if (!present.has(table)) {
      const ddl = catalog.tables.get(table);

      if (!ddl) {
        items.push({
          severity: 'blocking',
          table,
          kind: 'missing-table',
          detail:
            `Table "${table}" is missing and no recorded DDL was found for it. ` +
            (catalog.root
              ? `The migration history at ${catalog.root} does not create this table — it was ` +
                `probably added with \`db push\` instead of a migration.`
              : `No migrations directory was found. In a packaged build this means the ` +
                `prisma/migrations resource was not shipped; see electron-builder.yml.`)
        });
        continue;
      }

      missingTables.push(table);
      items.push({
        severity: 'additive',
        table,
        kind: 'missing-table',
        detail:
          `Table "${table}" is missing. Will be created from the DDL recorded in ` +
          `migration ${ddl.source}${ddl.indexSql.length ? ` (plus ${ddl.indexSql.length} index(es))` : ''}.`,
        // SQL is attached after ordering, below.
        sql: []
      });
      continue;
    }

    const live = await liveColumns(client, table);
    const liveByName = new Map(live.map((c) => [c.name, c]));

    // ---- Columns the schema expects but the database lacks ---------------
    for (const col of columns) {
      const actual = liveByName.get(col.name);

      if (!actual) {
        const canAdd = !col.required || col.defaultSql !== null || col.isUpdatedAt;

        if (!canAdd) {
          items.push({
            severity: 'blocking',
            table,
            column: col.name,
            kind: 'missing-column',
            detail:
              `Column "${table}"."${col.name}" (${col.sqliteType}) is required and has no ` +
              `default, so SQLite cannot add it to a table that already holds rows. ` +
              `This needs a migration that decides what value existing rows should get.`
          });
          continue;
        }

        // SQLite's ALTER TABLE ADD COLUMN requires a non-NULL default for any
        // NOT NULL column. @updatedAt fields have no schema-level default, but
        // CURRENT_TIMESTAMP is a correct starting value — Prisma overwrites it
        // on the next write.
        const defaultSql = col.defaultSql ?? (col.isUpdatedAt ? 'CURRENT_TIMESTAMP' : null);
        const nullability = col.required ? ` NOT NULL DEFAULT ${defaultSql}` : defaultSql ? ` DEFAULT ${defaultSql}` : '';

        const sql = [`ALTER TABLE "${table}" ADD COLUMN "${col.name}" ${col.sqliteType}${nullability}`];

        // UNIQUE cannot be declared in ADD COLUMN; add the index separately.
        if (col.isUnique) {
          sql.push(`CREATE UNIQUE INDEX IF NOT EXISTS "${table}_${col.name}_key" ON "${table}"("${col.name}")`);
        }

        items.push({
          severity: 'additive',
          table,
          column: col.name,
          kind: 'missing-column',
          detail:
            `Column "${table}"."${col.name}" ${col.sqliteType}` +
            `${col.required ? ' NOT NULL' : ''}${defaultSql ? ` DEFAULT ${defaultSql}` : ''} is missing.`,
          sql
        });
        continue;
      }

      // ---- Type comparison ------------------------------------------------
      const wanted = normaliseType(col.sqliteType);
      const found = normaliseType(actual.type);
      if (wanted !== found) {
        items.push({
          severity: 'blocking',
          table,
          column: col.name,
          kind: 'type-mismatch',
          detail:
            `Column "${table}"."${col.name}" is ${actual.type} in the database but the schema ` +
            `expects ${col.sqliteType}. Changing a column type in SQLite means rebuilding the ` +
            `table; that needs a migration with a data-conversion plan.`
        });
      }
    }

    // ---- Columns the database has but the schema dropped -----------------
    const expectedNames = new Set(columns.map((c) => c.name));
    for (const actual of live) {
      if (!expectedNames.has(actual.name)) {
        items.push({
          severity: 'info',
          table,
          column: actual.name,
          kind: 'extra-column',
          detail:
            `Column "${table}"."${actual.name}" exists in the database but not in the schema. ` +
            `Harmless — Prisma lists its columns explicitly — but it will not be backed up by ` +
            `a schema-driven export.`
        });
      }
    }
  }

  // ---- Attach table DDL in dependency order ------------------------------
  for (const table of orderByDependency(missingTables, catalog)) {
    const ddl = catalog.tables.get(table);
    const item = items.find((i) => i.kind === 'missing-table' && i.table === table && i.severity === 'additive');
    if (ddl && item) item.sql = [ddl.createSql, ...ddl.indexSql];
  }

  const additive = items.filter((i) => i.severity === 'additive');
  const blocking = items.filter((i) => i.severity === 'blocking');

  // CREATE TABLE before ALTER TABLE: a column added to a table created in this
  // same pass would otherwise fail, and the ordering keeps the log readable.
  const tableCreates = additive.filter((i) => i.kind === 'missing-table');
  const columnAdds = additive.filter((i) => i.kind !== 'missing-table');
  const orderedCreates = orderByDependency(
    tableCreates.map((i) => i.table),
    catalog
  ).map((t) => tableCreates.find((i) => i.table === t)!);

  return {
    ok: additive.length === 0 && blocking.length === 0,
    repairable: blocking.length === 0 && additive.length > 0,
    items,
    additive,
    blocking,
    repairSql: [...orderedCreates, ...columnAdds].flatMap((i) => i.sql ?? []),
    ddlSource: catalog.root
  };
}

// ---------------------------------------------------------------------------
// Repair
// ---------------------------------------------------------------------------

export interface RepairResult {
  applied: string[];
  failed: { sql: string; error: string }[];
  /**
   * Rows whose foreign keys point at something that does not exist, found by
   * PRAGMA foreign_key_check after the DDL. Empty is the expected result:
   * creating a missing table cannot orphan a row, but if the database was
   * already damaged this is where it surfaces.
   */
  foreignKeyViolations: { table: string; rowid: number | null; parent: string }[];
}

/**
 * Apply the additive statements from a report.
 *
 * The caller is responsible for taking a backup first — see
 * `SchemaGuard.ensureCompatible()` and `scripts/repair-runtime-schema.ts`.
 *
 * Statements are applied one at a time rather than in a transaction, on
 * purpose: SQLite executes DDL transactionally per statement, and a partial
 * ALTER sequence is still a strictly better database than the one we started
 * with. Anything that fails is reported and the caller decides whether to
 * restore.
 */
export async function applyRepair(client: PrismaClient, report: DriftReport): Promise<RepairResult> {
  const applied: string[] = [];
  const failed: { sql: string; error: string }[] = [];

  // Foreign key enforcement is disabled for the duration of the DDL. Creating
  // ten tables that reference one another cannot be done in an order that
  // satisfies every constraint at every intermediate step, and SQLite would
  // reject the sequence. Integrity is re-checked explicitly below rather than
  // assumed — the check is the point, not the PRAGMA.
  let fkWasOn = true;
  try {
    const rows = await client.$queryRawUnsafe<{ foreign_keys: number }[]>('PRAGMA foreign_keys');
    fkWasOn = rows?.[0]?.foreign_keys !== 0;
    await client.$executeRawUnsafe('PRAGMA foreign_keys=OFF');
  } catch {
    // Some drivers report PRAGMA reads oddly; proceeding is still correct.
  }

  for (const sql of report.repairSql) {
    try {
      await client.$executeRawUnsafe(sql);
      applied.push(sql);
    } catch (err: unknown) {
      failed.push({ sql, error: err instanceof Error ? err.message : String(err) });
    }
  }

  let foreignKeyViolations: RepairResult['foreignKeyViolations'] = [];
  try {
    const rows = await client.$queryRawUnsafe<
      { table: string; rowid: number | null; parent: string }[]
    >('PRAGMA foreign_key_check');
    foreignKeyViolations = (rows ?? []).map((r) => ({
      table: r.table,
      rowid: r.rowid ?? null,
      parent: r.parent
    }));
  } catch {
    // Not fatal: the DDL either applied or it did not, and that is reported.
  }

  if (fkWasOn) {
    try {
      await client.$executeRawUnsafe('PRAGMA foreign_keys=ON');
    } catch {
      /* best effort */
    }
  }

  return { applied, failed, foreignKeyViolations };
}

/** Human-readable summary for logs and for the CLI. */
export function formatReport(report: DriftReport): string {
  if (report.ok) return 'Database schema matches the Prisma datamodel.';

  const lines: string[] = [];
  if (report.blocking.length) {
    lines.push(`BLOCKING (${report.blocking.length}) — manual migration required:`);
    for (const i of report.blocking) lines.push(`  x ${i.detail}`);
  }
  if (report.additive.length) {
    lines.push(`ADDITIVE (${report.additive.length}) — safe to apply automatically:`);
    for (const i of report.additive) lines.push(`  + ${i.detail}`);
  }
  const info = report.items.filter((i) => i.severity === 'info');
  if (info.length) {
    lines.push(`INFO (${info.length}) — no action needed:`);
    for (const i of info) lines.push(`  . ${i.detail}`);
  }
  if (report.additive.some((i) => i.kind === 'missing-table')) {
    lines.push(`Recorded DDL source: ${report.ddlSource ?? 'none'}`);
  }
  return lines.join('\n');
}
